from __future__ import annotations

import logging
import time
from dataclasses import dataclass, field
from typing import Callable, Dict, List, Any, Protocol, Optional
from concurrent.futures import ProcessPoolExecutor, as_completed

import polars as pl
import numpy as np
from sklearn.metrics import mean_absolute_error, mean_squared_error


logger = logging.getLogger(__name__)


class ModelInterface(Protocol):
    def fit(self, df: pl.DataFrame) -> None: ...
    def predict(self, horizon: int) -> Any: ...

@dataclass(frozen=True)
class BacktestResult:
    """Immutable record of backtest performance."""
    strategy: str
    fold_metrics: List[Dict[str, float]]
    avg_mae: float
    avg_rmse: float
    volatility_mae: float  
    execution_time_sec: float

@dataclass
class RegimeComparison:
    """ comparison of Expanding vs Sliding behavior."""
    winning_strategy: str
    drift_detected: bool
    performance_gap: float

class TimeSeriesBacktester:

    def __init__(
        self,
        df: pl.DataFrame,
        datetime_column: str,
        target_column: str,
        forecast_horizon: int,
        product_column: Optional[str] = None,
        n_jobs: int = -1
    ):
        # CHANGED: added optional product_column. Panel data (multiple products
        # sharing one dataframe) must be sorted by [product, date], not just
        # date — sorting by date alone interleaves rows from different products
        # and makes row-count-based fold slicing (see _generate_folds) invalid,
        # since "row 100" no longer means "the same point in time" across
        # products of different lengths.
        self.product_column = product_column
        sort_cols = [product_column, datetime_column] if product_column else [datetime_column]
        self.df = df.sort(sort_cols)
        self.datetime_column = datetime_column
        self.target_column = target_column
        self.horizon = forecast_horizon
        self.n_jobs = n_jobs

    def run_backtest(
        self,
        strategy: str,
        model_factory: Callable[[], ModelInterface],
        initial_train_size: Optional[int] = None,
        window_size: Optional[int] = None,
        step: int = 1,
    ) -> BacktestResult:
        """
        Unified API for both strategies with performance logging.
        """
        start_ts = time.perf_counter()
        folds = self._generate_folds(strategy, initial_train_size, window_size, step)

        metrics = []

        for train, test in folds:
            fold_metric = self._evaluate_fold(model_factory, train, test)
            if fold_metric is not None:
                metrics.append(fold_metric)

        # CHANGED: previously, if every fold silently produced garbage (or the
        # loop body raised inside _evaluate_fold with no per-fold isolation),
        # _aggregate() would still run on whatever partial `metrics` existed,
        # or crash confusingly on an empty list via np.mean([]). Now a fold
        # can return None (see _evaluate_fold) and is skipped explicitly, and
        # we fail loudly with a clear message if literally nothing succeeded,
        # rather than returning a BacktestResult built from zero real folds.
        if not metrics:
            raise ValueError(
                f"Backtest produced zero usable folds for strategy='{strategy}'. "
                "Check that initial_train_size/window_size leave enough data "
                "for at least one fold given forecast_horizon="
                f"{self.horizon}."
            )

        duration = time.perf_counter() - start_ts
        return self._aggregate(strategy, metrics, duration)

    def _generate_folds(self, strategy: str, initial_size: int, window_size: int, step: int):
        # CHANGED: when product_column is set, folds are now generated by
        # DATE thresholds over the panel's unique dates, not by raw row count.
        # Row-count slicing (self.df[:end]) is only valid for a single
        # uninterrupted series. For a panel sorted by [product, date], "row
        # 100" is an arbitrary point that may land inside a completely
        # different product's history than "row 200" — it does not correspond
        # to a consistent point in time across the whole panel. Date-based
        # cutoffs guarantee every fold's train/test split respects the same
        # temporal boundary for every product simultaneously (train = all
        # rows, any product, before the cutoff date).
        if self.product_column is not None:
            unique_dates = self.df[self.datetime_column].unique().sort()
            total_dates = len(unique_dates)

            if strategy == "expanding":
                for end_idx in range(initial_size, total_dates - self.horizon, step):
                    cutoff = unique_dates[end_idx]
                    test_end = unique_dates[min(end_idx + self.horizon, total_dates - 1)]
                    train = self.df.filter(pl.col(self.datetime_column) < cutoff)
                    test = self.df.filter(
                        (pl.col(self.datetime_column) >= cutoff)
                        & (pl.col(self.datetime_column) <= test_end)
                    )
                    yield train, test

            elif strategy == "sliding":
                for start_idx in range(0, total_dates - window_size - self.horizon, step):
                    window_start = unique_dates[start_idx]
                    window_end = unique_dates[start_idx + window_size]
                    test_end = unique_dates[
                        min(start_idx + window_size + self.horizon, total_dates - 1)
                    ]
                    train = self.df.filter(
                        (pl.col(self.datetime_column) >= window_start)
                        & (pl.col(self.datetime_column) < window_end)
                    )
                    test = self.df.filter(
                        (pl.col(self.datetime_column) >= window_end)
                        & (pl.col(self.datetime_column) <= test_end)
                    )
                    yield train, test
            return

        # UNCHANGED: original row-count-based logic, kept as-is for the
        # single-series (no product_column) case — this remains correct
        # there since there's only one series to slice.
        if strategy == "expanding":
            for end in range(initial_size, self.df.height - self.horizon, step):
                yield self.df[:end], self.df[end : end + self.horizon]

        elif strategy == "sliding":
            for start in range(0, self.df.height - window_size - self.horizon, step):
                yield (
                    self.df[start : start + window_size],
                    self.df[start + window_size : start + window_size + self.horizon]
                )

    def _evaluate_fold(self, model_factory, train: pl.DataFrame, test: pl.DataFrame) -> Optional[Dict[str, float]]:
        model = model_factory()

        # CHANGED: this is the actual fix for the crash. The old code
        # unconditionally called `model.fit(train.to_pandas())` and
        # `model.make_future_dataframe(...)`, which only exist on ProphetModel.
        # XGBoostForecastModel.fit() requires a Polars DataFrame and has no
        # make_future_dataframe method at all — hence
        # "Input must be a Polars DataFrame". We now detect which contract the
        # model implements and branch accordingly, so both model types can be
        # backtested through the same TimeSeriesBacktester.
        is_prophet_style = hasattr(model, "make_future_dataframe")

        try:
            if is_prophet_style:
                # UNCHANGED: original Prophet-style path.
                model.fit(train.to_pandas())
                future_df = model.make_future_dataframe(
                    periods=self.horizon,
                    include_history=False,
                )
                forecast = model.predict(future_df)

                if isinstance(forecast, dict) and "yhat" in forecast:
                    y_pred = forecast["yhat"][-self.horizon:]
                elif hasattr(forecast, "forecast"):
                    y_pred = forecast.forecast["yhat"][-self.horizon:]
                elif hasattr(forecast, "yhat"):
                    y_pred = np.asarray(forecast.yhat)[-self.horizon:]
                else:
                    y_pred = forecast

                y_true = test[self.target_column].to_numpy()
                return self._compute_metrics(y_true, np.array(y_pred))

            else:
                # NEW: XGBoostForecastModel-style path. fit() takes Polars
                # directly (no .to_pandas()); predict() takes periods (and
                # optional products) and returns a ForecastResult covering
                # every product in the panel at once — there is no
                # make_future_dataframe/predict(df) step here.
                model.fit(train)
                forecast_result = model.predict(periods=self.horizon)
                pred_df = forecast_result.to_polars()

                # ForecastResult.to_polars() always emits fixed generic
                # column names ("date", "product", "yhat") regardless of the
                # real dataset's column names — same contract issue we fixed
                # in TemporalPipeline._evaluate_final(). Rename before joining.
                rename_map = {"date": self.datetime_column}
                if self.product_column is not None:
                    rename_map["product"] = self.product_column
                pred_df = pred_df.rename(rename_map)

                if self.product_column is not None:
                    joined = test.join(
                        pred_df, on=[self.product_column, self.datetime_column], how="inner"
                    )
                else:
                    joined = test.join(pred_df, on=self.datetime_column, how="inner")

                if joined.height == 0:
                    # A fold whose forecasted dates don't overlap this fold's
                    # test window can't be scored. Skip it rather than crash
                    # or silently feed empty arrays into sklearn's metrics.
                    logger.warning(
                        "[Backtest] Fold skipped — forecast/test join produced 0 rows "
                        "(train rows=%d, test rows=%d, forecast rows=%d).",
                        train.height, test.height, pred_df.height,
                    )
                    return None

                y_true = joined[self.target_column].to_numpy()
                y_pred = joined["yhat"].to_numpy()
                return self._compute_metrics(y_true, y_pred)

        except Exception as exc:
            # NEW: isolate a single fold's failure from the whole backtest.
            # Previously, any exception inside this method propagated straight
            # up through run_backtest() and out to _run_backtesting()'s
            # try/except in the pipeline, which then discarded ALL folds
            # (including ones that would have succeeded) with a single vague
            # "Walk-forward skipped" warning and zero detail. Now one bad fold
            # is logged with enough context to debug, and the backtest still
            # returns results from every fold that succeeded.
            logger.warning(
                "[Backtest] Fold failed (train rows=%d, test rows=%d): %s",
                train.height, test.height, exc,
            )
            return None

    def analyze_regime_change(
        self, 
        expanding_res: BacktestResult, 
        sliding_res: BacktestResult
    ) -> RegimeComparison:
        """
        Detects if the environment is changing (Concept Drift).
        Logic: If Sliding Window significantly outperforms Expanding, 
        old data is likely 'poisoning' the model with obsolete patterns.
        """
        gap = (expanding_res.avg_mae - sliding_res.avg_mae) / expanding_res.avg_mae
        
        drift = gap > 0.15
        winner = "sliding" if sliding_res.avg_mae < expanding_res.avg_mae else "expanding"
        
        logger.warning(f"Regime Analysis: Winner={winner}, Drift={drift}, Gap={gap:.2%}")
        
        return RegimeComparison(
            winning_strategy=winner,
            drift_detected=drift,
            performance_gap=gap
        )

    def _compute_metrics(self, y_true: np.ndarray, y_pred: np.ndarray) -> Dict[str, float]:
        return {
            "mae": float(mean_absolute_error(y_true, y_pred)),
            "rmse": float(np.sqrt(mean_squared_error(y_true, y_pred)))
        }

    def _aggregate(self, strategy: str, metrics: List[Dict[str, float]], duration: float) -> BacktestResult:
        maes = [m["mae"] for m in metrics]
        rmses = [m["rmse"] for m in metrics]
        
        return BacktestResult(
            strategy=strategy,
            fold_metrics=metrics,
            avg_mae=float(np.mean(maes)),
            avg_rmse=float(np.mean(rmses)),
            volatility_mae=float(np.std(maes)), 
            execution_time_sec=duration
        )